function buildCatalog() {
  const base = RABE3_I18N.en;
  for (const { code } of LANG_META) {
    if (!RABE3_I18N[code]) {
      RABE3_I18N[code] = { ...base, ...(PATCH[code] || {}) };
    } else if (PATCH[code]) {
      RABE3_I18N[code] = { ...RABE3_I18N[code], ...PATCH[code] };
    }
  }
  for (const [code, patch] of Object.entries(LANDING_PATCH)) {
    if (!RABE3_I18N[code]) RABE3_I18N[code] = { ...base, ...patch };
    else RABE3_I18N[code] = { ...RABE3_I18N[code], ...patch };
  }
}
