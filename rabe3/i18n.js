function applyLanguage(lang) {
  const pack = RABE3_I18N[lang] || RABE3_I18N.en;
  const rtl = RTL_LANGS.has(lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = rtl ? "rtl" : "ltr";
  document.title = pack.meta_title;
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = pack.meta_desc;

  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.content = pack.meta_title;
  const ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc && pack.meta_desc) ogDesc.content = pack.meta_desc;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(lang, key);
    if (val === key) return;
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") el.placeholder = val;
    else el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    const key = el.getAttribute("data-i18n-aria");
    const val = t(lang, key);
    if (val !== key) el.setAttribute("aria-label", val);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach(el => {
    const key = el.getAttribute("data-i18n-alt");
    const val = t(lang, key);
    if (val !== key) el.setAttribute("alt", val);
  });

  document.querySelectorAll(".theme-tile.premium").forEach((tile) => {
    tile.setAttribute("aria-label", t(lang, "theme_premium"));
  });

  // Chips
  document.querySelectorAll("[data-i18n-chips]").forEach(el => {
    const key = el.getAttribute("data-i18n-chips");
    const chips = pack[key];
    if (!Array.isArray(chips)) return;
    el.innerHTML = chips.map(c => `<span class="chip">${c}</span>`).join("");
  });

  // Lang menu active state
  document.querySelectorAll(".lang-menu button, .lang-menu .lang-option").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  document.querySelectorAll(".lang-pill").forEach((pill) => {
    const isActive = pill.dataset.lang === lang;
    pill.classList.toggle("active", isActive);
    pill.setAttribute("aria-pressed", isActive ? "true" : "false");
    const isPartial = !window.RABE3_FULL_LANDING_LANGS?.has(pill.dataset.lang);
    pill.classList.toggle("lang-pill--partial", isPartial);
    if (isPartial) pill.title = t(lang, "langs_landing_note");
    else pill.removeAttribute("title");
  });
  document.querySelectorAll(".faq-item.open .faq-answer").forEach((answer) => {
    answer.style.maxHeight = `${answer.scrollHeight}px`;
  });

  const langBtnLabel = document.getElementById("lang-btn-label");
  const meta = LANG_META.find(l => l.code === lang);
  if (langBtnLabel && meta) langBtnLabel.textContent = meta.label;

  const langExpand = document.getElementById("lang-expand");
  const langCloudEl = document.getElementById("lang-cloud");
  if (langExpand) {
    const expanded = langCloudEl?.classList.contains("is-expanded");
    langExpand.textContent = t(lang, expanded ? "langs_show_less" : "langs_show_all");
  }

  try {
    const url = new URL(location.href);
    url.searchParams.set("lang", lang);
    history.replaceState(null, "", url);
    const canonical = document.querySelector('link[rel="canonical"]');
    if (canonical) {
      const cUrl = new URL(canonical.href || location.href);
      cUrl.searchParams.set("lang", lang);
      canonical.href = cUrl.toString();
    }
  } catch (_) {}

  try { localStorage.setItem("rabe3-landing-lang", lang); } catch (_) {}
}

function initI18n() {
  let lang = "ar";
  try {
    const urlLang = new URLSearchParams(location.search).get("lang");
    if (urlLang && RABE3_I18N[urlLang]) {
      lang = urlLang;
    } else {
      const saved = localStorage.getItem("rabe3-landing-lang");
      const nav = navigator.language?.split("-")[0];
      if (saved && RABE3_I18N[saved]) lang = saved;
      else if (nav && RABE3_I18N[nav]) lang = nav;
    }
  } catch (_) {}
  applyLanguage(lang);
  return lang;
}

if (typeof window !== "undefined") {
  window.RABE3_LANG_META = LANG_META;
  window.RABE3_FULL_LANDING_LANGS = new Set(["en", "ar", "tr", "fr", "id", "ur", "de", "es", "zh", "ru", "fa", "ms"]);
  window.applyLanguage = applyLanguage;
  window.initI18n = initI18n;
  window.t = t;
}
